#!/usr/bin/env python3
"""Turn a song into beat / downbeat / hit markers for After Effects and DaVinci Resolve.

Outputs (next to the audio file, or in --out-dir):
  <name>_markers.jsx   After Effects: File > Scripts > Run Script File (adds comp or layer markers)
  <name>_markers.edl   Resolve: Media Pool > right-click timeline > Timelines > Import > Timeline Markers from EDL
  <name>_markers.csv   one row per marker (seconds, frame, timecode)
  <name>_markers.json  raw times, for other scripts

Engines:
  beat_this  most accurate beats + downbeats (pip install beat_this; needs PyTorch)
  librosa    lighter fallback (pip install librosa); downbeats are estimated as every 4th beat

Examples:
  python beats_to_markers.py song.wav --fps 25
  python beats_to_markers.py song.wav --fps 23.976 --mode downbeats
  python beats_to_markers.py drums.wav --fps 30 --mode hits      (run on a drum stem for kick/snare hits)
"""
import argparse
import csv
import json
import math
import os
import sys

RESOLVE_COLORS = {"downbeat": "ResolveColorRed", "beat": "ResolveColorBlue", "hit": "ResolveColorGreen"}
AE_LABELS = {"downbeat": 1, "beat": 8, "hit": 9}  # AE label colors: 1 red, 8 blue, 9 green


def detect_beat_this(path):
    from beat_this.inference import File2Beats  # noqa: WPS433 (optional dependency)

    device = "cpu"
    try:
        import torch

        if torch.cuda.is_available():
            device = "cuda"
    except ImportError:
        pass
    beats, downbeats = File2Beats(checkpoint_path="final0", device=device, dbn=False)(path)
    return [float(t) for t in beats], [float(t) for t in downbeats], None


def detect_librosa(path):
    import librosa
    import numpy as np

    y, sr = librosa.load(path, sr=None, mono=True)
    onset_env = librosa.onset.onset_strength(y=y, sr=sr)
    tempo, beat_frames = librosa.beat.beat_track(onset_envelope=onset_env, sr=sr)
    beats = librosa.frames_to_time(beat_frames, sr=sr)
    downbeats = []
    if len(beat_frames) >= 4:
        # Estimate the bar phase: the beat position (0-3) with the strongest onsets is taken as the downbeat.
        strength = onset_env[np.clip(beat_frames, 0, len(onset_env) - 1)]
        phase = int(np.argmax([strength[k::4].mean() for k in range(4)]))
        downbeats = beats[phase::4]
    tempo = float(np.atleast_1d(tempo)[0])
    return [float(t) for t in beats], [float(t) for t in downbeats], tempo


def detect_hits(path, min_gap):
    import librosa

    y, sr = librosa.load(path, sr=None, mono=True)
    hits = []
    for t in librosa.onset.onset_detect(y=y, sr=sr, units="time", backtrack=False):
        if not hits or t - hits[-1] >= min_gap:
            hits.append(float(t))
    return hits


def timecode(frame, base):
    ff = frame % base
    total_s = frame // base
    return f"{total_s // 3600:02d}:{(total_s // 60) % 60:02d}:{total_s % 60:02d}:{ff:02d}"


def parse_tc(tc, base):
    h, m, s, f = (int(x) for x in tc.replace(";", ":").split(":"))
    return ((h * 60 + m) * 60 + s) * base + f


def build_markers(beats, downbeats, hits, mode, fps):
    down = {round(t, 3) for t in downbeats}
    out = []
    if mode in ("beats", "all"):
        out += [(t, "downbeat" if round(t, 3) in down else "beat") for t in beats]
    elif mode == "downbeats":
        out += [(t, "downbeat") for t in downbeats]
    if mode in ("hits", "all"):
        out += [(t, "hit") for t in hits]
    out.sort(key=lambda m: m[0])
    counters = {}
    named = []
    for t, kind in out:
        counters[kind] = counters.get(kind, 0) + 1
        name = f"{kind} {counters[kind]}"
        # Editors keep one marker per frame, so merge markers that land on the same frame.
        if named and int(round(named[-1]["t"] * fps)) == int(round(t * fps)):
            prev = named[-1]
            prev["name"] += " + " + name
            if kind == "downbeat" or (kind == "beat" and prev["kind"] == "hit"):
                prev["kind"] = kind
            continue
        named.append({"t": t, "kind": kind, "name": name})
    return named


def write_jsx(path, markers, offset):
    rows = ",\n    ".join(
        f'[{m["t"] + offset:.4f}, "{m["name"]}", {AE_LABELS[m["kind"]]}]' for m in markers
    )
    js = f"""// TAWLIF beat markers. Generated by beats_to_markers.py
// Run: File > Scripts > Run Script File. Select the music layer first to put markers on it,
// or select nothing to put them on the composition.
(function () {{
  var comp = app.project.activeItem;
  if (!(comp && comp instanceof CompItem)) {{
    alert("Open the composition first, then run this script again.");
    return;
  }}
  var markers = [
    {rows}
  ];
  var layer = comp.selectedLayers.length ? comp.selectedLayers[0] : null;
  var prop = layer ? layer.property("Marker") : comp.markerProperty;
  var shift = layer ? layer.startTime : 0;
  app.beginUndoGroup("TAWLIF beat markers");
  for (var i = 0; i < markers.length; i++) {{
    var t = markers[i][0] + shift;
    if (t < 0 || t > comp.duration) continue;
    var mv = new MarkerValue(markers[i][1]);
    try {{ mv.label = markers[i][2]; }} catch (e) {{}}
    prop.setValueAtTime(t, mv);
  }}
  app.endUndoGroup();
}})();
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(js)


def write_edl(path, markers, fps, start_tc, title, offset):
    base = int(round(fps))
    start = parse_tc(start_tc, base)
    lines = [f"TITLE: {title}", "FCM: NON-DROP FRAME", ""]
    for i, m in enumerate(markers, 1):
        fr = start + int(round((m["t"] + offset) * fps))
        a, b = timecode(fr, base), timecode(fr + 1, base)
        lines.append(f"{i:03d}  001      V     C        {a} {b} {a} {b}  ")
        lines.append(f' |C:{RESOLVE_COLORS[m["kind"]]} |M:{m["name"]} |D:1')
        lines.append("")
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("audio", help="music or drum stem (wav recommended; mp3 decoding can shift timing)")
    ap.add_argument("--fps", type=float, default=25.0, help="timeline frame rate (default 25)")
    ap.add_argument("--mode", choices=["beats", "downbeats", "hits", "all"], default="beats")
    ap.add_argument("--engine", choices=["auto", "beat_this", "librosa"], default="auto")
    ap.add_argument("--offset", type=float, default=0.0, help="seconds to add to every marker (music start in the edit)")
    ap.add_argument("--resolve-start", default="01:00:00:00", help="Resolve timeline start timecode")
    ap.add_argument("--min-gap", type=float, default=0.1, help="hits mode: ignore hits closer than this many seconds")
    ap.add_argument("--out-dir", default=None)
    a = ap.parse_args(argv)

    if not os.path.isfile(a.audio):
        sys.exit(f"Audio file not found: {a.audio}")

    beats, downbeats, tempo, engine = [], [], None, None
    if a.mode != "hits":
        if a.engine in ("auto", "beat_this"):
            try:
                beats, downbeats, tempo = detect_beat_this(a.audio)
                engine = "beat_this"
            except ImportError:
                if a.engine == "beat_this":
                    sys.exit("beat_this is not installed. Run: pip install beat_this  (or use --engine librosa)")
        if engine is None:
            beats, downbeats, tempo = detect_librosa(a.audio)
            engine = "librosa (downbeats estimated)"
    hits = detect_hits(a.audio, a.min_gap) if a.mode in ("hits", "all") else []
    if engine is None:
        engine = "librosa onsets"

    markers = build_markers(beats, downbeats, hits, a.mode, a.fps)
    if not markers:
        sys.exit("No markers found. Try --mode hits on a drum stem, or check the audio file.")

    out_dir = a.out_dir or os.path.dirname(os.path.abspath(a.audio))
    os.makedirs(out_dir, exist_ok=True)
    stem = os.path.splitext(os.path.basename(a.audio))[0]
    base = os.path.join(out_dir, f"{stem}_markers")
    tc_base = int(round(a.fps))

    write_jsx(base + ".jsx", markers, a.offset)
    write_edl(base + ".edl", markers, a.fps, a.resolve_start, stem, a.offset)
    with open(base + ".csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["name", "kind", "seconds", "frame", "timecode"])
        for m in markers:
            fr = int(round((m["t"] + a.offset) * a.fps))
            w.writerow([m["name"], m["kind"], f"{m['t'] + a.offset:.4f}", fr, timecode(fr, tc_base)])
    with open(base + ".json", "w", encoding="utf-8") as f:
        json.dump({"source": os.path.basename(a.audio), "engine": engine, "fps": a.fps, "tempo": tempo,
                   "offset": a.offset, "beats": beats, "downbeats": downbeats, "hits": hits}, f, indent=1)

    bpm = f", about {tempo:.0f} BPM" if tempo and math.isfinite(tempo) else ""
    print(f"{len(markers)} markers ({engine}{bpm})")
    for ext in (".jsx", ".edl", ".csv", ".json"):
        print("  " + base + ext)


if __name__ == "__main__":
    main()
